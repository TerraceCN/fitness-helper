// ===== 配额表类型 =====

export interface QuotaTable {
  heights: number[]
  weights: number[]
  /** data[weightIdx][heightIdx] = QuotaEntry | null (- 表示无数据) */
  data: (QuotaEntry | null)[][]
}

// ===== 配额表数据 =====

/** 解析 CSV 单元格 "trainCarbs/restCarbs/protein" → QuotaEntry, "-" → null */
function p(cell: string): QuotaEntry | null {
  if (cell === '-') return null
  const [a, b, c] = cell.split('/').map(Number)
  return { trainingDayCarbs: a!, restDayCarbs: b!, protein: c! }
}

