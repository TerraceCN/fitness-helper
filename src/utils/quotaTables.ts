// ===== 数据校验 =====

const TABLE_NAMES: Record<string, string> = {
  MALE_CUT: '男性-减脂',
  MALE_BULK: '男性-增肌',
  FEMALE_CUT: '女性-减脂',
  FEMALE_BULK: '女性-增肌',
}

function validateQuotaTable(table: QuotaTable, name: string): void {
  const heightCount = table.heights.length
  const weightCount = table.weights.length

  // 行数 = weights 数量
  if (table.data.length !== weightCount) {
    throw new Error(
      `[配额表校验] ${name}: data 行数(${table.data.length})与 weights 数量(${weightCount})不匹配`,
    )
  }

  // 每行列数 = heights 数量
  for (let w = 0; w < table.data.length; w++) {
    if (table.data[w]!.length !== heightCount) {
      throw new Error(
        `[配额表校验] ${name}: data 第${w}行列数(${table.data[w]!.length})与 heights 数量(${heightCount})不匹配`,
      )
    }
  }
}

const ALL_TABLES: { table: QuotaTable; name: string }[] = [
  { table: MALE_CUT, name: 'MALE_CUT' },
  { table: MALE_BULK, name: 'MALE_BULK' },
  { table: FEMALE_CUT, name: 'FEMALE_CUT' },
  { table: FEMALE_BULK, name: 'FEMALE_BULK' },
]

for (const { table, name } of ALL_TABLES) {
  validateQuotaTable(table, TABLE_NAMES[name]!)
}
